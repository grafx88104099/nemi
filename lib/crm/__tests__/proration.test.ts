import { describe, expect, it } from "vitest";

import {
  daysInMonth,
  monthStart,
  nextMonthStart,
  occupiedDaysInMonth,
  prorate,
  terminationAdjustment,
} from "@/lib/crm/proration";

describe("proration — туслахууд", () => {
  it("сарын эхлэл/дараагийн сар/хоногийн тоо", () => {
    expect(monthStart("2026-03-15")).toBe("2026-03-01");
    expect(monthStart("2026-03")).toBe("2026-03-01");
    expect(nextMonthStart("2026-12-05")).toBe("2027-01-01");
    expect(daysInMonth("2026-01-01")).toBe(31);
    expect(daysInMonth("2026-04-01")).toBe(30);
    expect(daysInMonth("2026-02-01")).toBe(28);
    expect(daysInMonth("2028-02-01")).toBe(29); // өндөр жил
  });

  it("хамрах хоног — '[)' семантик: дуусах өдөр тооцогдохгүй", () => {
    // 3-р сарын 10-наас 3-р сарын 20 хүртэл → 10 хоног (10..19).
    expect(occupiedDaysInMonth("2026-03-10", "2026-03-20", "2026-03")).toBe(10);
    // Бүтэн сар.
    expect(occupiedDaysInMonth("2026-01-01", "2027-01-01", "2026-03")).toBe(31);
    // Огт хамрахгүй.
    expect(occupiedDaysInMonth("2026-05-01", "2026-06-01", "2026-03")).toBe(0);
    // Гэрээ сарын 1-нд дуусвал тэр сард 0 хоног.
    expect(occupiedDaysInMonth("2026-01-01", "2026-03-01", "2026-03")).toBe(0);
  });
});

describe("prorate (F-585)", () => {
  it("бүтэн сар → бүтэн дүн", () => {
    expect(prorate(2_000_000, "2026-01-01", "2027-01-01", "2026-03")).toBe(2_000_000);
    // Яг сарын мужтай давхцах гэрээ.
    expect(prorate(2_000_000, "2026-03-01", "2026-04-01", "2026-03")).toBe(2_000_000);
  });

  it("сарын дундуур эхлэх — үлдсэн хоногоор хувь тэнцүүлнэ", () => {
    // 3-р сарын 16-наас: 16 хоног (16..31) / 31.
    expect(prorate(3_100_000, "2026-03-16", "2027-03-16", "2026-03")).toBe(
      Math.round(((3_100_000 * 16) / 31) * 100) / 100
    );
  });

  it("сарын дундуур дуусах — эхний хоногоор", () => {
    // 4-р сарын 11-нд дуусна → 10 хоног (1..10) / 30.
    expect(prorate(3_000_000, "2025-04-11", "2026-04-11", "2026-04")).toBe(1_000_000);
  });

  it("28/29/30/31 хоногтой саруудад хуваарь зөв", () => {
    // 2-р сарын 15-наас (2026: 28 хоног) → 14 хоног.
    expect(prorate(2_800_000, "2026-02-15", "2027-02-15", "2026-02")).toBe(1_400_000);
    // Өндөр жилийн 2-р сар (2028: 29 хоног) → 15 хоног (15..29).
    expect(prorate(2_900_000, "2028-02-15", "2029-02-15", "2028-02")).toBe(1_500_000);
    // 30 хоногтой сар.
    expect(prorate(3_000_000, "2026-06-16", "2027-06-16", "2026-06")).toBe(1_500_000);
    // 31 хоногтой сар: 17..31 = 15 хоног.
    expect(prorate(3_100_000, "2026-07-17", "2027-07-17", "2026-07")).toBe(1_500_000);
  });

  it("хамрахгүй сар → 0 (сул сард нэхэмжлэхгүй Д-14-ийн тооцооллын тал)", () => {
    expect(prorate(2_000_000, "2026-05-01", "2026-06-01", "2026-03")).toBe(0);
  });

  it("сөрөг дүнд алдаа шиднэ", () => {
    expect(() => prorate(-1, "2026-01-01", "2026-02-01", "2026-01")).toThrow();
  });
});

describe("terminationAdjustment (дундуур цуцлалт — F-514в)", () => {
  it("бүтэн сараар нэхэмжилснээс илүү төлбөрийг буцаана", () => {
    // 3 сая/сар, 4-р сарын 16-нд цуцлагдсан (1..15 = 15 хоног / 30 → 1.5 сая ногдоно).
    expect(terminationAdjustment(3_000_000, 3_000_000, "2026-04-01", "2026-04-16", "2026-04")).toBe(
      1_500_000
    );
  });

  it("цуцлалт сарын сүүлч бол залруулга 0", () => {
    expect(terminationAdjustment(3_000_000, 3_000_000, "2026-04-01", "2026-05-01", "2026-04")).toBe(0);
  });
});
